// Brand names and site kinds (pure, dependency-free apart from the generated seed). The owner's seed file
// (src/lib/brands/seed.tsv → seed.gen.ts) gives every tracked brand a display name and a site kind; the stored
// library_sites.name wins when set. Reader-facing text calls a brand by its name; the domain stays the link and the id.
import { BRAND_SEED } from "./brands/seed.gen";

export const SITE_KINDS = ["standard", "merchandised", "editorial"] as const;
export type SiteKind = (typeof SITE_KINDS)[number];
export const isSiteKind = (v: unknown): v is SiteKind => typeof v === "string" && (SITE_KINDS as readonly string[]).includes(v);
/** What each kind means for the story engine (rules.ts, /what-we-show). */
export const SITE_KIND_RULE = {
  standard: "Every kind of change can count toward a story.",
  merchandised: "A storefront homepage: its accent, palette, hero and headline follow the top promotion or product, so changes to those go to the tape only. A change of typeface or layout can still count.",
  editorial: "A media homepage: its palette and hero follow the day's lead story, so changes to those go to the tape only. A change of typeface or layout can still count.",
} as const satisfies Record<SiteKind, string>;

export type SeedRow = { domain: string; name: string; kind: SiteKind };
/** Parse the seed file: one brand per line, tab-separated domain, name, kind. Throws on a malformed line. */
export function parseSeed(tsv: string): SeedRow[] {
  return tsv.split(/\r?\n/).filter(l => l.trim()).map((l, i) => {
    const [domain, name, kind, ...rest] = l.split("\t").map(x => x.trim());
    if (!domain || !name || !isSiteKind(kind) || rest.length) throw new Error(`seed line ${i + 1} is malformed`);
    return { domain: domain.toLowerCase(), name, kind };
  });
}
export const seedModule = (rows: SeedRow[]) =>
  `// Generated by scripts/build-brand-seed.ts from src/lib/brands/seed.tsv. Do not edit by hand.\nexport const BRAND_SEED: readonly (readonly [domain: string, name: string, kind: "standard" | "merchandised" | "editorial"])[] = [\n${rows.map(r => `  [${JSON.stringify(r.domain)}, ${JSON.stringify(r.name)}, ${JSON.stringify(r.kind)}],`).join("\n")}\n];\n`;

const SEED = new Map(BRAND_SEED.map(([d, n, k]) => [d, { name: n, kind: k as SiteKind }]));
export const seededDomains = () => [...SEED.keys()];
const bare = (d: string) => d.trim().toLowerCase().replace(/^https?:\/\//, "").replace(/^www\./, "").replace(/\/.*$/, "");

/** A tidy form of a domain for a brand without a name: the registrable label, capitalised ("acme-labs.co.uk" → "Acme-labs"). */
export function tidyDomain(domain: string): string {
  const parts = bare(domain).split(".").filter(Boolean);
  if (!parts.length) return domain;
  // Drop the public suffix (one label, or two for "co.uk"-style endings).
  const two = parts.length >= 3 && parts.at(-2)!.length <= 3 && parts.at(-1)!.length === 2;
  const label = parts.length === 1 ? parts[0]! : parts[parts.length - (two ? 3 : 2)]!;
  return label.charAt(0).toUpperCase() + label.slice(1);
}
/** The brand's display name: the stored name, else the seed name, else a tidy form of the domain. */
export function brandName(domain: string, stored?: string | null): string {
  const s = typeof stored === "string" ? stored.trim() : "";
  return s || SEED.get(bare(domain))?.name || tidyDomain(domain);
}
/** The brand's site kind: the stored kind, else the seed kind, else standard. */
export function siteKind(domain: string, stored?: string | null): SiteKind {
  return isSiteKind(stored) ? stored : SEED.get(bare(domain))?.kind ?? "standard";
}

const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
let seedRe: RegExp | null = null;
const reFor = (domains: string[]) => new RegExp(`(?<![\\p{L}\\p{N}@/._-])(?:www\\.)?(${[...domains].sort((a, b) => b.length - a.length).map(esc).join("|")})(?![\\p{L}\\p{N}_-]|\\.[\\p{L}\\p{N}]|/)`, "giu");
/**
 * Reader-facing text with every bare tracked domain replaced by the brand's name ("docusign.com changed its accent" → "DocuSign
 * changed its accent"). Links, e-mail addresses, paths and sub-domains are left alone. `names` overrides the seed (stored names).
 */
export function nameText(text: string, names?: ReadonlyMap<string, string | null>): string;
export function nameText(text: string | null, names?: ReadonlyMap<string, string | null>): string | null;
export function nameText(text: string | null, names?: ReadonlyMap<string, string | null>): string | null {
  if (!text) return text;
  const extra = names ? [...names.keys()].filter(d => !SEED.has(d)) : [];
  const re = extra.length ? reFor([...SEED.keys(), ...extra]) : (seedRe ??= reFor([...SEED.keys()]));
  re.lastIndex = 0;
  return text.replace(re, (_m, d: string) => brandName(d.toLowerCase(), names?.get(d.toLowerCase()) ?? null));
}
/** True when a text still carries a bare tracked domain (tests and checks). */
export const hasBareDomain = (text: string) => nameText(text) !== text;
