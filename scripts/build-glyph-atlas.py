# Builds src/lib/chart/glyphs.gen.ts: deflated Geist Mono alpha masks for the server-side card rasterizer.
# Usage: python3 scripts/build-glyph-atlas.py /path/GeistMono-400.(ttf|woff) /path/GeistMono-600.(ttf|woff)
import sys, zlib, base64, struct
from PIL import Image, ImageDraw, ImageFont
SIZES = [22, 28, 44, 96]
EXTRA = "·—–→←▲▼≥≤±…Δ×’‘“”éèêëáàâäíìîïóòôöúùûüñçøåÉÖÜÄß"
CHARS = "".join(chr(c) for c in range(32, 127)) + EXTRA
def mask(font, ch):
    l, t, r, b = font.getbbox(ch)
    if r <= l or b <= t: return 0, 0, 0, 0, b""
    im = Image.new("L", (r - l, b - t), 0)
    ImageDraw.Draw(im).text((-l, -t), ch, font=font, fill=255)
    return r - l, b - t, l, t, im.tobytes()
out = {}
chars = None
for weight, path in zip((400, 600), sys.argv[1:3]):
    for size in SIZES:
        font = ImageFont.truetype(path, size)
        missing = mask(font, "\ue000")[4]
        keep = [c for c in CHARS if c == " " or mask(font, c)[4] != missing]
        chars = chars or "".join(keep)
        blob = bytearray()
        for c in chars:
            w, h, l, t, data = mask(font, c)
            blob += struct.pack("<HHhh", w, h, l, t) + data
        out[f"{weight}-{size}"] = base64.b64encode(zlib.compress(bytes(blob), 9)).decode()
font = ImageFont.truetype(sys.argv[1], 1000)
asc, desc = font.getmetrics()
lines = ["// Generated by scripts/build-glyph-atlas.py from Geist Mono (SIL OFL 1.1). Do not edit.",
         f"export const GLYPH_CHARS = {chars!r};".replace("'", '"') if '"' not in chars else "export const GLYPH_CHARS = " + repr(chars) + ";",
         f"export const GLYPH_SIZES = {SIZES} as const;",
         f"export const GLYPH_ADVANCE = {font.getlength('M') / 1000};",
         f"export const GLYPH_ASCENT = {asc / 1000};",
         "export const GLYPH_ATLASES: Record<string, string> = {"]
lines += [f'  "{k}": "{v}",' for k, v in out.items()] + ["};", ""]
open("src/lib/chart/glyphs.gen.ts", "w").write("\n".join(lines))
print(len(chars), sum(len(v) for v in out.values()))
