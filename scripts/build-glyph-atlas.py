# Builds src/lib/chart/glyphs.gen.ts: deflated alpha masks for the server-side image drawer (share cards, OG images).
#   IBM Plex Mono 400/600 (the utility face, code-like values) at every size: GLYPH_ATLASES, fixed advance.
#   Big Shoulders 700/900 (headlines, figures) and Newsreader 400 (decks): FACE_ATLASES with per-glyph advance widths, each
#   instanced at its optical size (opsz = the pixel size, clamped to the axis), as browsers do with font-optical-sizing: auto.
# Usage: python3 scripts/build-glyph-atlas.py IBMPlexMono-Regular.ttf IBMPlexMono-SemiBold.ttf "BigShoulders[opsz,wght].ttf" "Newsreader[opsz,wght].ttf"
import sys, zlib, base64, struct, io
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
SIZES = [22, 28, 44, 96]
FACES = {  # face -> (font file index, weight -> sizes)
    "display": (3, {700: [22, 28, 44], 900: [44, 96]}),
    "text": (4, {400: [22, 28]}),
}
EXTRA = "·—–→←▲▼≥≤±…Δ×’‘“”éèêëáàâäíìîïóòôöúùûüñçøåÉÖÜÄß"
CHARS = "".join(chr(c) for c in range(32, 127)) + EXTRA
def mask(font, ch):
    l, t, r, b = font.getbbox(ch)
    if r <= l or b <= t: return 0, 0, 0, 0, b""
    im = Image.new("L", (r - l, b - t), 0)
    ImageDraw.Draw(im).text((-l, -t), ch, font=font, fill=255)
    return r - l, b - t, l, t, im.tobytes()
def pack(font, chars, cmap=None):
    blob = bytearray()
    for c in chars:
        d = c if cmap is None or ord(c) in cmap else "?"
        w, h, l, t, data = mask(font, d)
        blob += struct.pack("<HHhh", w, h, l, t) + data
    return base64.b64encode(zlib.compress(bytes(blob), 9)).decode()
out = {}
chars = None
for weight, path in zip((400, 600), sys.argv[1:3]):
    for size in SIZES:
        font = ImageFont.truetype(path, size)
        missing = mask(font, "\ue000")[4]
        keep = [c for c in CHARS if c == " " or mask(font, c)[4] != missing]
        chars = chars or "".join(keep)
        out[f"{weight}-{size}"] = pack(font, chars)
mono = ImageFont.truetype(sys.argv[1], 1000)
asc, desc = mono.getmetrics()
faces, advances, ascents = {}, {}, {}
for face, (idx, weights) in FACES.items():
    src = TTFont(sys.argv[idx])
    axes = {a.axisTag: (a.minValue, a.maxValue) for a in src["fvar"].axes}
    cmap = src.getBestCmap()
    for weight, sizes in weights.items():
        for size in sizes:
            lo, hi = axes["opsz"]
            inst = instancer.instantiateVariableFont(TTFont(sys.argv[idx]), {"wght": weight, "opsz": max(lo, min(hi, size))})
            buf = io.BytesIO(); inst.save(buf); buf.seek(0)
            font = ImageFont.truetype(buf, size)
            key = f"{face}-{weight}-{size}"
            faces[key] = pack(font, chars, cmap)
            # Advance widths in 1/16 px, in GLYPH_CHARS order (a missing glyph takes "?").
            advances[key] = [round(font.getlength(c if ord(c) in cmap else "?") * 16) for c in chars]
            if face not in ascents:
                buf.seek(0); big = ImageFont.truetype(buf, 1000); a, _ = big.getmetrics(); ascents[face] = a / 1000
lines = ["// Generated by scripts/build-glyph-atlas.py from IBM Plex Mono, Big Shoulders and Newsreader (all SIL OFL 1.1). Do not edit.",
         "export const GLYPH_CHARS = " + repr(chars) + ";" if '"' in chars else f"export const GLYPH_CHARS = \"{chars}\";",
         f"export const GLYPH_SIZES = {SIZES} as const;",
         f"export const GLYPH_ADVANCE = {mono.getlength('M') / 1000};",
         f"export const GLYPH_ASCENT = {asc / 1000};",
         "export const GLYPH_ATLASES: Record<string, string> = {"]
lines += [f'  "{k}": "{v}",' for k, v in out.items()] + ["};"]
lines += ["/** Ascent (em) per proportional face, at the 1000-unit instance. */",
          "export const FACE_ASCENT: Record<string, number> = " + "{ " + ", ".join(f'"{k}": {round(v, 4)}' for k, v in ascents.items()) + " };",
          "/** Advance widths in 1/16 px per atlas, in GLYPH_CHARS order. */",
          "export const FACE_ADVANCES: Record<string, readonly number[]> = {"]
lines += [f'  "{k}": [{",".join(map(str, v))}],' for k, v in advances.items()] + ["};"]
lines += ["export const FACE_ATLASES: Record<string, string> = {"]
lines += [f'  "{k}": "{v}",' for k, v in faces.items()] + ["};", ""]
open("src/lib/chart/glyphs.gen.ts", "w").write("\n".join(lines))
print(len(chars), sum(len(v) for v in out.values()), sum(len(v) for v in faces.values()))
