// Builds src/components/brand/filters.gen.ts from the owner's illustration filters (brand/illustration/slug-filters.svg).
// Run: bun scripts/build-filters.ts. The module inlines the kit's <defs> once per page that draws an illustration; illustration.test.ts
// checks it matches the file, exactly as the mark module is checked against brand/logo/svg.
import { readFileSync, writeFileSync } from "node:fs";
import { parseFilterSvg } from "../src/components/brand/filter-file";

const { defs, ids } = parseFilterSvg(readFileSync("brand/illustration/slug-filters.svg", "utf8"));
writeFileSync("src/components/brand/filters.gen.ts", `// Generated by scripts/build-filters.ts from brand/illustration/slug-filters.svg. Do not edit.\nexport const FILTER_IDS = ${JSON.stringify(ids)} as const;\nexport const FILTER_DEFS = ${JSON.stringify(defs)};\n`);
console.log(ids.join(", "));
