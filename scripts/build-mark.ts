// Builds src/components/brand/mark.gen.ts from the owner's outlined logo files (brand/logo/svg). Run: bun scripts/build-mark.ts
// The mark is a drawing, not type: the app inlines these paths and never sets the name in a font. mark.test.ts checks the module matches the files.
import { readFileSync, writeFileSync } from "node:fs";
import { MARK_FILES, parseMarkSvg } from "../src/components/brand/mark-files";

const out: Record<string, { w: number; h: number; d: string }> = {};
for (const [cut, file] of Object.entries(MARK_FILES)) out[cut] = parseMarkSvg(readFileSync(`brand/logo/svg/${file}`, "utf8"));
const body = Object.entries(out).map(([k, v]) => `  ${k}: { w: ${v.w}, h: ${v.h}, d: ${JSON.stringify(v.d)} },`).join("\n");
writeFileSync("src/components/brand/mark.gen.ts", `// Generated by scripts/build-mark.ts from brand/logo/svg (outlined from Shrikhand, SIL OFL 1.1). Do not edit.\nexport const MARK_PATHS = {\n${body}\n} as const;\n`);
console.log(Object.keys(out).join(", "));
